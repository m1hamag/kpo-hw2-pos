// DemoInput возвращает ввод демо-сценария и печатает каждую строку в out,
// как будто её набрал пользователь
func DemoInput(out io.Writer) io.Reader {
	return &echoReader{lines: demoScript, out: out}
}

type echoReader struct {
	lines   []string
	out     io.Writer
	pending []byte // непрочитанный остаток текущей строки
}

func (r *echoReader) Read(p []byte) (int, error) {
	if len(r.pending) == 0 {
		if len(r.lines) == 0 {
			return 0, io.EOF
		}
		r.pending = []byte(r.lines[0] + "\n")
		r.lines = r.lines[1:]
		if _, err := r.out.Write(r.pending); err != nil {
			return 0, err
		}
	}
	n := copy(p, r.pending)
	r.pending = r.pending[n:]
	return n, nil
}
